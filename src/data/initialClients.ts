export function parseClientsFromCSV(csvText: string): ClientRecord[] {
  const lines = csvText.split(/\r?\n/).filter((l) => l.trim().length > 0);
  if (lines.length <= 1) return [];

  const clients: ClientRecord[] = [];

  // Identify delimiter
  const firstLine = lines[0];
  const delimiter = firstLine.includes(';') ? ';' : firstLine.includes('\t') ? '\t' : ',';

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i];
    const cols = line.split(delimiter).map((c) => c.trim().replace(/^"|"$/g, ''));
    if (cols.length < 2) continue;

    const name = cols[0];
    const id = cols[1];
    if (!name || !id) continue;

    const professor = cols[2] || '';
    const consultor = cols[3] || '';
    const personal = cols[4] || '';
    const status = cols[5] || 'Ativo';
    const sisterName = cols[6] || '';
    const motherName = cols[7] || '';

    clients.push({
      id,
      name,
      professor,
      consultor,
      personal,
      status: status.trim() || 'Ativo',
      sisterName,
      motherName,
      notes: [
        professor ? `Professor: ${professor}` : '',
        consultor ? `Consultor: ${consultor}` : '',
        personal ? `Personal: ${personal}` : '',
      ]
        .filter(Boolean)
        .join(' • '),
    });
  }

  return clients;
}

